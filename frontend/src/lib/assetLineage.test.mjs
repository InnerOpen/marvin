// An asset's lineage line (assetLineage.ts).

import assert from "node:assert/strict";
import { test } from "node:test";

import { describeDerivation, lineageOf } from "./assetLineage.ts";

test("a media step's derivation reads as words", () => {
  assert.equal(describeDerivation("media:resize:fit=inside,format=webp,width=800"), "resize webp, 800 wide");
  assert.equal(describeDerivation("media:crop:aspect=1:1,focus=subject"), "crop 1:1, on the subject");
  assert.equal(describeDerivation("media:convert:format=webp,quality=82"), "convert webp, quality 82");
  assert.equal(describeDerivation("grade:rustic-warm"), "grade rustic-warm");
});

test("a derivative and a generated image have a lineage; an original has none", () => {
  assert.deepEqual(
    lineageOf({ derived_from: "a1", derivation: "media:grade:preset=warm", workflow_slug: "brand-recolor" }),
    {
      sourceId: "a1",
      made: "grade warm",
      workflow: "brand-recolor",
      prompt: null,
    },
  );
  assert.deepEqual(
    lineageOf({
      derivation: "generated:openai_images.generate",
      generated_by: "openai_images.generate",
      prompt: "A harbour",
    }),
    {
      sourceId: null,
      made: "generated by openai_images.generate",
      workflow: null,
      prompt: "A harbour",
    },
  );
  assert.equal(lineageOf({ credit: "Ada" }), null);
  assert.equal(lineageOf(null), null);
});

// An asset's lineage line (assetLineage.ts).

import assert from "node:assert/strict";
import { test } from "node:test";

import { assetRefs, describeDerivation, lineageOf, metaLink } from "./assetLineage.ts";

test("a media step's derivation reads as words", () => {
  assert.equal(describeDerivation("media:resize:fit=inside,format=webp,width=800"), "resize webp, 800 wide");
  assert.equal(describeDerivation("media:crop:aspect=1:1,focus=subject"), "crop 1:1, on the subject");
  assert.equal(describeDerivation("media:convert:format=webp,quality=82"), "convert webp, quality 82");
  assert.equal(describeDerivation("grade:rustic-warm"), "grade rustic-warm");
});

test("a derivative and a generated image have a lineage; an original has none", () => {
  assert.deepEqual(
    lineageOf({ derived_from: "a1", derivation: "media:grade:preset=warm", workflow_slug: "brand-recolor" }),
    {
      sourceId: "a1",
      made: "grade warm",
      model: null,
      workflow: "brand-recolor",
      workflowId: null,
      entryId: null,
      prompt: null,
    },
  );
  assert.deepEqual(
    lineageOf({
      derivation: "generated:openai_images.generate",
      generated_by: "openai_images.generate",
      prompt: "A harbour",
      model: "gpt-image-2",
      made_for_entry: "5d63bcdb-a0c7-4114-a723-eac545832148",
      workflow_id: "4fbdc1cf-749d-461c-9ada-6576e116b9c4",
      workflow_slug: "alternate-universe-cover",
      correlation_id: "843621fb4de641c7874179ceac3fb653",
    }),
    {
      sourceId: null,
      made: "generated by openai_images.generate",
      model: "gpt-image-2",
      workflow: "alternate-universe-cover",
      workflowId: "4fbdc1cf-749d-461c-9ada-6576e116b9c4",
      entryId: "5d63bcdb-a0c7-4114-a723-eac545832148",
      prompt: "A harbour",
    },
  );
  assert.equal(lineageOf({ credit: "Ada" }), null);
  assert.equal(lineageOf(null), null);
});

test("assetRefs: the pictures a version or a render was made from, as links", () => {
  const a = "3f1c2a4e-1b2c-4d5e-8f90-123456789abc";
  const b = "9a8b7c6d-5e4f-4a3b-9c2d-0123456789ab";
  assert.deepEqual(assetRefs("derived_from", a), [a]);
  assert.deepEqual(assetRefs("rendered_from", { background: a, tiles: [b, a] }), [a, b]); // each once
  assert.deepEqual(assetRefs("derived_from", "not-an-id"), []);
  assert.deepEqual(assetRefs("workflow_id", a), []); // only the keys that name assets
});

test("an edited picture says what edited it", () => {
  assert.equal(describeDerivation("edited:openai_images.edit"), "edited by openai_images.edit");
});

test("metaLink: the entry a picture was made for and the workflow that made it open where they live", () => {
  const entry = "5d63bcdb-a0c7-4114-a723-eac545832148";
  const wf = "4fbdc1cf-749d-461c-9ada-6576e116b9c4";
  assert.deepEqual(metaLink("made_for_entry", entry), { kind: "entry", href: `/workspace/entries/${entry}` });
  assert.deepEqual(metaLink("workflow_id", wf), { kind: "workflow", href: `/automation/workflows?workflow=${wf}` });
  assert.equal(metaLink("correlation_id", "843621fb4de641c7874179ceac3fb653"), null); // not an id, and no page for it
  assert.equal(metaLink("made_for_entry", "not-an-id"), null);
  assert.equal(metaLink("derived_from", entry), null); // assets go through assetRefs
});

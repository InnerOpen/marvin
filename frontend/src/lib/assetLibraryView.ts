// The Assets library's view, kept in the URL: which filters are on, the sort, whether versions are folded under their
// original. The page reads it on the server, asks the API for exactly those assets, and links ("3 versions", "Back to
// all") are made from it. Pure, so `npm test` covers it (assetLibraryView.test.mjs).

export interface LibraryView {
  q: string;
  type: string;
  origin: string;
  /** What an approval said about the picture: approved, denied, expired, stale, none (never asked). */
  decision: string;
  tag: string;
  collection: string;
  /** "" any, "yes" on an entry, "no" on no entry */
  attached: string;
  sort: string;
  /** Show versions as their own rows (else folded under their original). */
  versions: boolean;
  /** Show the versions made from this asset (an id). */
  source: string;
  /** "trashed": the Trash instead of the library. */
  status: string;
}

export const SORTS: Record<string, string> = { name: "Name", newest: "Newest", oldest: "Oldest", largest: "Largest" };
export const ORIGINS: Record<string, string> = {
  upload: "Uploaded",
  derived: "Made from another image",
  generated: "Generated by AI",
};
export const DECISIONS: Record<string, string> = {
  approved: "Approved",
  denied: "Denied",
  expired: "Not decided in time",
  stale: "Approved too late",
  none: "Never asked",
};
export const TYPES: Record<string, string> = {
  image: "Images",
  svg: "SVGs",
  video: "Videos",
  audio: "Audio",
  document: "Documents",
  archive: "Archives",
  other: "Other",
};

const pick = (value: string | null, allowed: Record<string, string>) => (value && value in allowed ? value : "");

export function readLibraryView(params: URLSearchParams): LibraryView {
  const text = (k: string) => (params.get(k) ?? "").trim();
  return {
    q: text("q"),
    type: pick(params.get("type"), TYPES),
    origin: pick(params.get("origin"), ORIGINS),
    decision: pick(params.get("decision"), DECISIONS),
    tag: text("tag"),
    collection: text("collection"),
    attached: ["yes", "no"].includes(text("attached")) ? text("attached") : "",
    sort: pick(params.get("sort"), SORTS) || "name",
    versions: params.get("versions") === "show",
    source: text("source"),
    status: text("status") === "trashed" ? "trashed" : "",
  };
}

/** What to ask GET /api/platform/assets for. Versions fold away unless shown, filtered to, or asked for by source. */
export function listParams(view: LibraryView): Record<string, string | boolean | string[]> {
  const out: Record<string, string | boolean | string[]> = { sort: view.sort };
  if (view.q) out.q = view.q;
  if (view.type) out.asset_type = [view.type];
  if (view.origin) out.origin = [view.origin];
  if (view.decision) out.decision = view.decision;
  if (view.tag) out.tag = [view.tag];
  if (view.collection) out.collection = view.collection;
  if (view.attached) out.unattached = view.attached === "no";
  if (view.source) out.source = view.source;
  else if (!view.versions && view.origin !== "derived") out.versions = false;
  return out;
}

/** A link to this view with some filters changed ("" or false drops one). */
export function viewHref(view: LibraryView, changes: Partial<LibraryView> = {}, path = "/workspace/assets"): string {
  const next = { ...view, ...changes };
  const qs = new URLSearchParams();
  for (const key of ["q", "type", "origin", "decision", "tag", "collection", "attached", "source", "status"] as const) {
    if (next[key]) qs.set(key, next[key]);
  }
  if (next.sort && next.sort !== "name") qs.set("sort", next.sort);
  if (next.versions) qs.set("versions", "show");
  const s = qs.toString();
  return s ? `${path}?${s}` : path;
}

/** Whether any filter narrows the list (so an empty result says "nothing matches", not "no assets yet"). */
export function isFiltered(view: LibraryView): boolean {
  return Boolean(view.q || view.type || view.origin || view.decision || view.tag || view.collection || view.attached || view.source);
}

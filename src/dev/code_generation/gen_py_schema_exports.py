"""Generate the re-exports in `src/marvin/schemas/<package>/__init__.py`.

Run with `task dev:generate`. A package is generated only when its `__init__.py` opens with the
header below; a package with a hand-written `__init__.py` (a docstring, a curated subset of its
modules) is left alone. Every class defined at the top level of a package's modules is exported:
files and classes are sorted (case-insensitively, like ruff's import sort), so the output is deterministic and `tests/test_schema_exports.py`
fails when a committed `__init__.py` drifts from it.
"""

import re
import subprocess
import sys
from pathlib import Path

HEADER = "# This file is auto-generated by gen_py_schema_exports.py"
OWNED_PREFIX = "# This file is auto-generated by"

PROJECT_DIR = Path(__file__).resolve().parents[3]
SCHEMA_PATH = PROJECT_DIR / "src" / "marvin" / "schemas"


def package_classes(package: Path) -> dict[str, list[str]]:
    """Maps each public-facing module in `package` to its sorted top-level class names."""
    modules: dict[str, list[str]] = {}
    for file in sorted(package.glob("*.py")):
        if file.name.startswith("_"):
            continue
        classes = sorted(re.findall(r"(?m)^class\s(\w+)", file.read_text()), key=str.lower)
        if classes:
            modules[file.stem] = classes
    return modules


def render(package: Path) -> str:
    """The formatted `__init__.py` for `package`."""
    modules = package_classes(package)

    owners: dict[str, str] = {}
    for module, classes in modules.items():
        for name in classes:
            if name in owners:
                raise SystemExit(f"{package.name}: {name} is defined in both {owners[name]}.py and {module}.py")
            owners[name] = module

    lines = [HEADER]
    lines += [f"from .{module} import {', '.join(classes)}" for module, classes in modules.items()]
    lines += ["", "__all__ = ["]
    lines += [f'    "{name}",' for classes in modules.values() for name in classes]
    lines += ["]", ""]

    # The project's own ruff config (found through the filename) decides import order, line length and quoting.
    destination = str(package / "__init__.py")
    source = "\n".join(lines)
    for command in (["check", "--select", "I001", "--fix"], ["format"]):
        source = subprocess.run(
            [sys.executable, "-m", "ruff", *command, "--stdin-filename", destination, "-"],
            input=source,
            capture_output=True,
            text=True,
            check=True,
        ).stdout
    return source


def generated_packages() -> list[Path]:
    """Schema packages whose `__init__.py` is owned by this generator."""
    return sorted(init.parent for init in SCHEMA_PATH.glob("*/__init__.py") if init.read_text().startswith(OWNED_PREFIX))


def main() -> None:
    for package in generated_packages():
        (package / "__init__.py").write_text(render(package))
        print(f"generated {package.relative_to(PROJECT_DIR)}/__init__.py")


if __name__ == "__main__":
    main()
